import {execFileSync} from 'node:child_process'
import {readFileSync,writeFileSync} from 'node:fs'
const {flow}=JSON.parse(readFileSync('output/v1/final-ui-manifest.json','utf8'))
async function edits(page,flow){
  await page.goto(`http://127.0.0.1:5175/flows/${flow}/versions/3`,{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'可视化编排',exact:true}).click()
  await page.locator('.canvas-node').filter({hasText:'黑名单校验'}).click()
  await page.getByLabel('命中原因码',{exact:true}).fill('V1_OPERATOR_EDIT')
  await page.locator('.inspector').getByRole('button',{name:'下移',exact:true}).click()
  await page.locator('.inspector').getByRole('button',{name:'上移',exact:true}).click()
  await page.locator('.canvas-node').filter({hasText:'订单准入规则'}).click()
  await page.getByRole('button',{name:'编辑完整配置',exact:true}).click()
  await page.locator('[data-field="matchPolicy"]').selectOption('ALL_MATCH')
  const amountRule=page.locator('[data-item-id="r_amount"]')
  await amountRule.locator('.config-condition-toggle').click()
  await amountRule.locator('[data-field="value"]').fill('{')
  if(!await amountRule.locator('.field-error').count())throw new Error('invalid condition JSON not shown')
  await amountRule.locator('[data-field="value"]').fill('49999')
  await amountRule.locator('[data-field="value"]').fill('50000')
  if(await amountRule.locator('.field-error').count())throw new Error('condition correction did not clear error')
  await page.getByRole('button',{name:'+ 添加规则',exact:true}).click()
  const added=page.locator('.config-edit-card').last(),newRuleId=await added.getAttribute('data-item-id')
  if(!newRuleId.startsWith('rule_'))throw new Error('rule not added')
  await added.getByRole('button',{name:'删除',exact:true}).click()
  await page.locator('[data-item-id="r_amount"]').getByRole('button',{name:'下移',exact:true}).click()
  await page.locator('[data-item-id="r_amount"]').getByRole('button',{name:'上移',exact:true}).click()
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('.canvas-node').filter({hasText:'买家风险评分卡'}).click()
  await page.getByRole('button',{name:'编辑完整配置',exact:true}).click()
  await page.locator('[data-item-id="b_refund_high"]').getByRole('button',{name:'下移',exact:true}).click()
  await page.locator('[data-item-id="b_refund_high"]').getByRole('button',{name:'上移',exact:true}).click()
  await page.getByRole('button',{name:'+ 添加维度',exact:true}).click()
  const dimension=page.locator('.config-characteristic').last(),dimensionId=await dimension.getAttribute('data-item-id')
  if(!dimensionId.startsWith('char_'))throw new Error('dimension not added')
  await dimension.getByRole('button',{name:'删除维度',exact:true}).click()
  const refund=page.locator('[data-item-id="c_refund"]')
  await refund.locator('.config-card-head').getByRole('button',{name:'上移',exact:true}).click()
  await refund.locator('.config-card-head').getByRole('button',{name:'下移',exact:true}).click()
  const highBin=page.locator('[data-item-id="b_refund_high"]')
  await highBin.locator('.config-condition-toggle').click()
  await highBin.locator('[data-field="value"]').fill('0.31')
  await highBin.locator('[data-field="value"]').fill('0.3')
  await refund.getByRole('button',{name:'+ 添加分箱',exact:true}).click()
  const newBin=refund.locator('.config-edit-card').last(),newBinId=await newBin.getAttribute('data-item-id')
  if(!newBinId.startsWith('bin_'))throw new Error('bin not added')
  await newBin.getByRole('button',{name:'删除',exact:true}).click()
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('.canvas-node').filter({hasText:'订单金额分层'}).click()
  await page.getByRole('button',{name:'编辑完整配置',exact:true}).click()
  await page.locator('[data-item-id="t_high"] [data-field="reasonCode"]').fill('V1_TABLE_EDIT')
  await page.getByRole('button',{name:'+ 添加条件行',exact:true}).click()
  const newTableRule=page.locator('.config-edit-card').last(),tableRuleId=await newTableRule.getAttribute('data-item-id')
  await newTableRule.getByRole('button',{name:'删除',exact:true}).click()
  const tableHigh=page.locator('[data-item-id="t_high"]')
  await tableHigh.getByRole('button',{name:'下移',exact:true}).click()
  await tableHigh.getByRole('button',{name:'上移',exact:true}).click()
  await tableHigh.locator('.config-condition-toggle').click()
  await tableHigh.locator('[data-field="value"]').fill('5001')
  await tableHigh.locator('[data-field="value"]').fill('5000')
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('.canvas-node').filter({hasText:'通过交易'}).click()
  await page.getByLabel('原因码（逗号分隔）',{exact:true}).fill('RISK_ACCEPTABLE, V1_TERMINAL_EDIT')
  await page.getByRole('button',{name:'保存草稿',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.notice')?.textContent.includes('草稿已保存'))
  await page.reload({waitUntil:'domcontentloaded'})
  const r=await(await page.request.get(`http://127.0.0.1:8081/api/v2/admin/flows/${flow}/versions/3`)).json()
  const nodes=r.document.stages.flatMap(s=>s.nodes),node=id=>nodes.find(n=>n.nodeId===id)
  if(r.document.stages.length!==6||nodes.length!==8||!r.validation.valid)throw new Error('structural edits not restored')
  if(node('blacklist').config.reasonCode!=='V1_OPERATOR_EDIT'||node('base_rules').config.matchPolicy!=='ALL_MATCH'||node('order_segment').config.rules[0].reasonCode!=='V1_TABLE_EDIT'||!node('approve').config.reasonCodes.includes('V1_TERMINAL_EDIT'))throw new Error('five node config edits lost')
  if(node('buyer_score').config.characteristics[1].bins[0].id!=='b_refund_high')throw new Error('reorder changed stable bin identity')
  if(JSON.stringify(r.document).includes(newRuleId)||JSON.stringify(r.document).includes(newBinId)||JSON.stringify(r.document).includes(dimensionId)||JSON.stringify(r.document).includes(tableRuleId))throw new Error('deleted rows persisted')
  await page.getByRole('button',{name:'输入事实',exact:true}).click()
  await page.getByLabel('facts JSON').fill('{"order":{"amount":50000,"country":"XX"},"risk":{"blacklisted":false}}')
  const pending=page.waitForResponse(r=>r.url().endsWith('/simulations'))
  await page.getByRole('button',{name:'保存并试运行',exact:true}).first().click()
  const result=await(await pending).json()
  if(result.decision.decisionCode!=='REJECT'||result.nodeResults.find(n=>n.nodeId==='base_rules').details.length!==2)throw new Error('UI ALL_MATCH not applied')
  await page.screenshot({path:'output/playwright/v1-editor-all-match.png',fullPage:true})
  return {status:'PASS',flow,revision:r.revision,tests:['Operator/RuleSet/Scorecard/DecisionTable/Terminal UI edits persisted','rule/bin/dimension/table-row add/delete/reorder stable IDs','collapsed conditions expand and edit; invalid JSON corrected before save','node order down/up','UI ALL_MATCH yields two hit details'],details:result.nodeResults.find(n=>n.nodeId==='base_rules').details}
}
const result=execFileSync(process.env.PWCLI??'/Users/ycr/.codex/skills/playwright/scripts/playwright_cli.sh',['-s=v1','run-code',`async(page)=>await (${edits.toString()})(page,${JSON.stringify(flow)})`],{encoding:'utf8',timeout:65000,maxBuffer:2e6})
writeFileSync('output/v1/editor-browser.txt',result)
if(result.includes('### Error')||!result.includes('"status":"PASS"'))throw new Error(result)
console.log(result)
